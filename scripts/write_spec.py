"""Generate reports/golden_model_spec.md from the golden-model constants and E4 ranges."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from snnsim import fixed as FX  # noqa: E402


def fmt_range(d, key, unit=""):
    if not d or key not in d:
        return "n/a"
    r = d[key]
    f = lambda x: "n/a" if x is None else f"{x:.4g}"
    lo = r.get("min_all", r.get("p0"))
    hi = r.get("max_all", r.get("p100"))
    parts = [f"min {f(lo)}"] if lo is not None else []
    for q in ("p1", "p50", "p99", "p99.9"):
        if q in r:
            parts.append(f"{q} {f(r[q])}")
    parts.append(f"max {f(hi)}")
    return ", ".join(parts) + (f" {unit}" if unit else "")


def main():
    e4 = {}
    for c in ["a_float", "l_hw"]:
        p = os.path.join(ROOT, "results", f"e4_{c}.json")
        if os.path.exists(p):
            e4[c] = json.load(open(p))
    K = {dt: FX.FixedConsts(dt).as_dict() for dt in (1e-4, 2e-4, 5e-4)}
    L = []
    w = L.append
    w("# SpikeNav golden model — fixed-point arithmetic specification")
    w("")
    w("Bit-exact reference: `golden_c/snn_golden.c` (C99) == `snnsim/engine.py` with `arith='fixed'`")
    w("(checked by `tests/test_golden_c.py`). Network: VPRSNN test-mode module (784 inputs, 400 E, 400 I;")
    w("https://github.com/QVPR/VPRSNN, MIT License). This file is generated by `scripts/write_spec.py`.")
    w("")
    w("## 1. Number formats")
    w("")
    w("| Quantity | Storage | LSB (real value) | Range / saturation |")
    w("|---|---|---|---|")
    w(f"| membrane potential v (E and I) | signed int32 (25 bits used) | 2^-{FX.VF} mV | saturate to [{FX.V_MIN}, {FX.V_MAX}] = ±256 mV |")
    w(f"| conductances ge_E, gi_E, ge_I | unsigned, int32 (23 bits used) | 1/{FX.GU} (= 1/(255·16)) | saturate to [0, {FX.G_MAX}] (≈2056) |")
    w("| input weight (8-bit) | uint8 code c | w = c/255 | increment ge by c·16 (exact) |")
    w("| input weight (4-bit) | uint4 code c | w = c/15 | increment ge by c·272 (exact) |")
    w("| E firing threshold THR[j] | signed int32 per neuron | 2^-16 mV | THR = floor((θ_j[mV] − 72)·2^16 + 0.5) |")
    w("| refractory / timer counters | unsigned, saturating | 1 step | any cap ≥ T_LOCK gives identical results (10 bits suffice at dt = 0.1 ms) |")
    w("| delay-ring accumulators | signed int64 in the model; ≤ 24 bits needed (see ranges) | 1/4080 | — |")
    w("")
    w("Helper operations (all integer): `asr(x,s)` = arithmetic shift right (floor division by 2^s);")
    w("`rshr(x,s) = asr(x + 2^(s-1), s)` (round half up). Products are formed in 64-bit.")
    w("")
    w("## 2. One integration step (Brian2 schedule; all updates of phase 1 use the old state)")
    w("")
    w("```")
    w("Phase 1 — neuron update, for every neuron j:")
    w("  since_e[j]++, since_i[j]++, timer[j]++                 (saturating)")
    w("  nre = since_e[j] >= REF_E ;  nri = since_i[j] >= REF_I")
    w("  E: if nre:")
    w(f"       C   = gi_E * asr(E_INH - v_E, {FX.VS}) - ge_E * asr(v_E, {FX.VS})")
    w("       acc = KV_E * (V_REST_E - v_E) + KC_E * C")
    w(f"       v_E = sat(v_E + rshr(acc, {FX.SH}))")
    w(f"     ge_E = asr(ge_E * DGE, {FX.GSH}) ;  gi_E = asr(gi_E * DGI, {FX.GSH})")
    w("  I: if nri:")
    w(f"       acc = KV_I * (V_REST_I - v_I) - KC_I * (ge_I * asr(v_I, {FX.VS}))")
    w(f"       v_I = sat(v_I + rshr(acc, {FX.SH}))")
    w(f"     ge_I = asr(ge_I * DGE, {FX.GSH})")
    w("Phase 2 — thresholds (on the updated values):")
    w("  sI[j] = (v_I > V_TH_I) and nri")
    w("  sE[j] = (v_E > THR[j]) and (timer[j] >= T_LOCK) and nre")
    w("  input spikes of this step from the spike generator (Section 4)")
    w("Phase 3 — synapses:")
    w("  for each input spike i, for each j: ring[slot(i,j)][j] += INC[i][j]")
    w("      slot = (t + d[i][j]) mod S                         (0.1 ms or 1 ms-multiple delays)")
    w("      slot = ((t div SPM) + 1 + d_ms[i][j]) * SPM mod S  (1 ms binned delivery, proposed HW)")
    w("  ge_E[j] = min(ge_E[j] + ring[t mod S][j], G_MAX) ; ring[t mod S][j] = 0")
    w("  ge_I[j] = min(ge_I[j] + W_EI * sE[j], G_MAX)                       (E->I one-to-one)")
    w("  gi_E[j] = min(gi_E[j] + W_IE * (N_I - sI[j]), G_MAX), N_I = sum_j sI[j]  (I->E all-but-self)")
    w("Phase 4 — resets: if sE[j]: v_E = V_RESET_E, timer = 0, since_e = 0, count[j]++")
    w("                  if sI[j]: v_I = V_RESET_I, since_i = 0")
    w("t = t + 1")
    w("```")
    w("")
    w("Hard reset at the start of every module run (proposed hardware): v_E = V_REST_E, v_I = V_REST_I,")
    w("all conductances 0, all counters saturated (neurons immediately eligible), ring buffer cleared, t = 0.")
    w("A module run is n_present = 350 ms / dt steps of input; the output is count[j] over those steps.")
    w("(Reference carry-over mode instead starts with v = V_INIT, timer = 0, a 0.5 s rest, and 150 ms rests.)")
    w("")
    w("## 3. Constants")
    w("")
    w("Derived from dt with round-half-up (`floor(x+0.5)`); identical in C and Python.")
    w("")
    w("| Constant | Meaning | dt = 0.1 ms | dt = 0.2 ms | dt = 0.5 ms |")
    w("|---|---|---|---|---|")
    meaning = {"V_REST_E": "-65 mV", "V_RESET_E": "-65 mV", "V_REST_I": "-60 mV", "V_RESET_I": "-45 mV",
               "V_TH_I": "-40 mV", "E_INH_E": "-100 mV", "V_INIT_E": "-105 mV (carry mode only)",
               "V_INIT_I": "-100 mV (carry mode only)", "KV_E": "round(dt/τe·2^30), τe=100 ms",
               "KV_I": "round(dt/τi·2^30), τi=10 ms", "KC_E": "round(dt/τe·2^7/4080·2^30)",
               "KC_I": "round(dt/τi·2^7/4080·2^30)", "DGE": "round((1−dt/1 ms)·2^16)",
               "DGI": "round(max(0,1−dt/0.5 ms)·2^16)", "W_EI": "round(10.4·4080)", "W_IE": "17·4080",
               "REF_E": "5 ms in steps", "REF_I": "2 ms in steps",
               "T_LOCK": "first k with k·(0.1·dt) > 5 ms in float64 (Brian2 timer quirk)"}
    for n in K[1e-4]:
        w(f"| {n} | {meaning.get(n, '')} | {K[1e-4][n]} | {K[2e-4][n]} | {K[5e-4][n]} |")
    w("")
    w("Note the Brian2 timer quirk: `dtimer/dt = 0.1`, so the 5 ms `timer > refrac_e` condition needs 50 ms of")
    w("simulated time; with float64 accumulation the first step that satisfies it is k = 501 at dt = 0.1 ms.")
    w("")
    w("## 4. Hash and spike generator (multiplier-free except the final range reduction)")
    w("")
    w("```")
    w("mix32(h): h += h<<10; h ^= h>>6; h += h<<3; h ^= h>>11; h += h<<15     (mod 2^32)")
    w("delay hash: h = mix32(mix32(((i<<9) | j) XOR module_seed)) ; h16 = h >> 16")
    w("  0.1 ms delays : d = (h16 * (MAXD+1)) >> 16, MAXD = 10 ms/dt   (101 values at dt=0.1 ms)")
    w("  1 ms delays   : d_ms = (h16 * 11) >> 16 (0..10 ms); multiply by 11 = (x<<3)+(x<<1)+x")
    w("spike generator: 16 xorshift32 generators (x^=x<<13; x^=x>>17; x^=x<<5)")
    w("  generator g serves pixels g, g+16, ..., g+16*48 in that order, one draw per pixel per step")
    w("  seed_g = mix32(mix32(stream*16 + g) XOR 0xA5A5A5A5), forced to 1 if zero")
    w("  stream = (poisson_seed<<26) | (session<<24) | (module<<16) | query   (module = 255: shared train)")
    w("  spike(pixel i) = (x >> 8) < THRP[i],  THRP[i] = floor(pixel_i/4 * dt * 2^24 + 0.5)")
    w("```")
    w("")
    w("## 5. Measured value ranges (E4, all 12 test modules x 100 test queries)")
    w("")
    for c, d in e4.items():
        w(f"**{c}** (source `results/e4_{c}.json`):")
        w("")
        w(f"- v_E: {fmt_range(d, 'v_e_mV', 'mV')}")
        w(f"- ge_E: {fmt_range(d, 'ge_e')}")
        w(f"- gi_E: {fmt_range(d, 'gi_e')}")
        w(f"- v_I: {fmt_range(d, 'v_i_mV', 'mV')}")
        w(f"- ge_I: {fmt_range(d, 'ge_i')}")
        w(f"- θ: {fmt_range(d, 'theta_mV', 'mV')}")
        w("")
    w("Headroom check: the chosen formats cover ±256 mV for v and up to ≈2056 for conductances; the")
    w("measured extremes above stay inside these limits (saturation never engages in the measured runs")
    w("if max |v| < 256 mV and max g < 2056).")
    w("")
    w("## 6. Operand widths for an RTL implementation")
    w("")
    w(f"- asr(v, {FX.VS}) is an 18-bit signed operand (|v| < 256 mV); diff = asr(E_INH − v, {FX.VS}) likewise.")
    w("- ge/gi operands: width set by the measured maxima above (ge_E, ge_I, gi_E); gi_E peaks are the widest.")
    w("- KV_*, KC_* fit in 24 bits; products C (≤ ~41 bits) × KC (≤ 19 bits) need a 64-bit (or 2×DSP cascaded) accumulator.")
    w("- Multiplies per neuron-step: E = 6 (gi·diff, ge·vq, KV·(Vr−v), KC·C, ge·DGE, gi·DGI); I = 4 (ge·vq, KC·(..), KV·(Vr−v), ge·DGE).")
    w("  DGE/DGI multiplies are by constants and may be replaced by shift-add networks in RTL only if bit-exactness")
    w("  with this specification is preserved (i.e. compute exactly g·DGE).")
    os.makedirs(os.path.join(ROOT, "reports"), exist_ok=True)
    with open(os.path.join(ROOT, "reports", "golden_model_spec.md"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote reports/golden_model_spec.md")


if __name__ == "__main__":
    main()
